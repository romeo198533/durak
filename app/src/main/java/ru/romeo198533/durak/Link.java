package ru.romeo198533.durak;

import java.io.IOException;

/**
 * Канал связи: строки туда и обратно.
 *
 * Всё, что знает партия о проводе, — эти четыре действия. Блютус, вай-фай и
 * канал в одной памяти выглядят для неё одинаково, поэтому партия проверяется
 * на памяти, а на телефоне поверх того же самого надевается настоящее радио.
 *
 * Читающий ждёт: {@link #read()} возвращается, только когда строка пришла или
 * связь кончилась. Значит, звать его можно не из того потока, который рисует
 * экран, — иначе экран замрёт вместе с игрой.
 */
public interface Link {

    /** Отправить строку. */
    void send(String line) throws IOException;

    /**
     * Прочитать строку, дождавшись её.
     *
     * @return строка или null, если тот конец закрылся.
     */
    String read() throws IOException;

    void close();

    /** Кто на том конце — для экрана: «телефон Валеры». */
    String name();
}
