    @Override
    protected void onCreate(Bundle state) {
        super.onCreate(state);
        setTitle("Инструкция");

        LinearLayout root = Skin.column(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.setPadding(Skin.dp(this, 10), Skin.dp(this, 8),
                Skin.dp(this, 10), Skin.dp(this, 24));

        for (String paragraph : PARAGRAPHS) {
            root.addView(line(paragraph));
        }

        // Версия — последней строкой: её называют, когда что-то не работает, и
        // искать её по экрану не должно быть отдельным делом.
        String version = About.version(this);
        if (!version.isEmpty()) {
            root.addView(line("#Версия " + version));
        }

        ScrollView scroll = new ScrollView(this);
        scroll.addView(root);
        setContentView(scroll);
    }

    /** Один абзац инструкции: заголовок — крупнее и жирным. */
    private TextView line(String paragraph) {
        boolean heading = paragraph.startsWith(HEADING);
        String text = heading ? paragraph.substring(HEADING.length()).trim() : paragraph;

        TextView view = Skin.text(this, text, heading ? 20 : 17);
        // Строки инструкции читают глазами редко, но листают пальцем: по левому
        // краю абзац легче поймать касанием, чем по середине экрана.
        view.setGravity(Gravity.START);
        view.setPadding(0, Skin.dp(this, heading ? 18 : 6),
                0, Skin.dp(this, heading ? 6 : 6));
        if (heading) {
            view.setTypeface(Typeface.DEFAULT_BOLD);
            // «Заголовок» вслух — чтобы на слух было слышно, где кончился один
            // раздел и начался другой.
            view.setContentDescription(text + ". Заголовок.");
        } else {
            view.setContentDescription(text);
        }
        view.setLayoutParams(new LinearLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.WRAP_CONTENT));
        return view;
    }
